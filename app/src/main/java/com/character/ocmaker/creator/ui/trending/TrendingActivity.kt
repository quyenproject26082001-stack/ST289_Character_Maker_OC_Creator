        override fun onResume() {
            super.onResume()
            if (isAnimating && !InternetHelper.isInternetAvailable(this)) {
                interruptGenerationForNoInternet()
            }
            lifecycleScope.launch {
                lifecycle.withResumed { showPendingNoInternet() }
            }
        }


