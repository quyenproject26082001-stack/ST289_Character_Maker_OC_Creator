        private fun initData() {
            val handleExceptionCoroutine = CoroutineExceptionHandler { _, throwable ->
                CoroutineScope(Dispatchers.Main).launch {
                    val dialogExit = YesNoDialog(
                        this@TrendingActivity,
                        R.string.error,
                        R.string.an_error_occurred
                    )
                    dialogExit.show()
                    dialogExit.onNoClick = {
                        dialogExit.dismiss()
                        finish()
                    }
                    dialogExit.onYesClick = {
                        dialogExit.dismiss()
                        hideNavigation()
                        finish()
                    }
                }
            }

            CoroutineScope(SupervisorJob() + Dispatchers.Main + handleExceptionCoroutine).launch {
                val t0 = System.currentTimeMillis()
                android.util.Log.d(
                    "TIMING_TRENDING",
                    "initData() START (allData.size=${dataViewModel.allData.value.size})"
                )

                val internetStart = System.currentTimeMillis()
                val hasInternet = withContext(Dispatchers.IO) {
                    InternetHelper.isInternetAvailable(this@TrendingActivity)
                }
                android.util.Log.d(
                    "TIMING_TRENDING",
                    "  [Step1] internetCheck: ${System.currentTimeMillis() - internetStart}ms | hasInternet=$hasInternet"
                )

                if (!hasInternet) {
                    dismissLoading()
                    showNoInternetDialog()
                    return@launch
                }

                val filteredData = dataViewModel.allData.value
                android.util.Log.d(
                    "TIMING_TRENDING",
                    "  filteredData.size=${filteredData.size} (allData.size=${dataViewModel.allData.value.size}, hasInternet=$hasInternet)"
                )
                if (filteredData.isEmpty()) {
                    android.util.Log.w("TIMING_TRENDING", "  filteredData rỗng → return")
                    return@launch
                }

                suspend fun processCharacter(
                    summary: com.character.ocmaker.creator.data.model.custom.CustomizeModel
                ) {
                    val data = dataViewModel.getCharacter(
                        this@TrendingActivity,
                        summary
                    ) ?: return
                    customizeCharacterViewModel.positionSelected =
                        dataViewModel.allData.value.indexOf(summary)
                    customizeCharacterViewModel.setDataCustomize(data)
                    customizeCharacterViewModel.updateAvatarPath(data.avatar)
                    customizeCharacterViewModel.resetDataList()
                    customizeCharacterViewModel.addValueToItemNavList()
                    customizeCharacterViewModel.setItemColorDefault()
                    val allNavList = data.layerList.mapIndexed { index, layer ->
                        com.character.ocmaker.creator.data.model.custom.NavigationModel(
                            imageNavigation = layer.imageNavigation,
                            layerIndex = index
                        )
                    }.toCollection(ArrayList())
                    allNavList.firstOrNull()?.isSelected = true
                    customizeCharacterViewModel.setBottomNavigationList(allNavList)
                    for (j in 0 until ValueKey.RANDOM_QUANTITY) {
                        customizeCharacterViewModel.setClickRandomFullLayer()
                        val suggestion = customizeCharacterViewModel.getSuggestionList()
                        viewModel.updateRandomList(suggestion)
                    }
                }

                // Xử lý character đầu tiên → show ngay
                val processFirstStart = System.currentTimeMillis()
                withContext(Dispatchers.IO) {
                    try {
                        processCharacter(filteredData[0])
                    } catch (e: Exception) {
                        e.printStackTrace()
                    }
                    viewModel.upsideDownList()
                }
                android.util.Log.d(
                    "TIMING_TRENDING",
                    "  [Step2] processCharacter[0] (${filteredData[0].dataName}, isFromAPI=${filteredData[0].isFromAPI}): ${System.currentTimeMillis() - processFirstStart}ms | randomList.size=${viewModel.randomList.size}"
                )

                android.util.Log.d(
                    "TIMING_TRENDING",
                    "  [Step3] processFirst DONE: ${System.currentTimeMillis() - t0}ms"
                )
                if (!generateOnEntryIfReady()) {
                    dismissLoading()
                }

                // Xử lý phần còn lại ở background
                if (filteredData.size > 1) {
                    val bgStart = System.currentTimeMillis()
                    withContext(Dispatchers.IO) {
                        for (i in 1 until filteredData.size) {
                            val charStart = System.currentTimeMillis()
                            try {
                                processCharacter(filteredData[i])
                            } catch (e: Exception) {
                                e.printStackTrace()
                            }
                            android.util.Log.d(
                                "TIMING_TRENDING",
                                "  [BG] processCharacter[$i] (${filteredData[i].dataName}): ${System.currentTimeMillis() - charStart}ms"
                            )
                        }
                        viewModel.upsideDownList()
                    }
                    android.util.Log.d(
                        "TIMING_TRENDING",
                        "  [BG] tất cả characters còn lại: ${System.currentTimeMillis() - bgStart}ms | randomList.size=${viewModel.randomList.size}"
                    )
                }
                android.util.Log.d(
                    "TIMING_TRENDING",
                    "initData() COMPLETE | tổng: ${System.currentTimeMillis() - t0}ms"
                )
                generateOnEntryIfReady()
            }
        }

        private fun generateOnEntryIfReady(): Boolean {
            if (hasAutoGenerated || viewModel.randomList.isEmpty()) return false
            hasAutoGenerated = true
            handleGenerate()
            return true
        }

        private fun clearGeneratedResult() {
            currentSuggestion = null
            Glide.with(this).clear(binding.imvImage)
            binding.imvImage.setImageDrawable(null)
            binding.guidRandom.visible()
            binding.btnEdit.isEnabled = false
            binding.btnEdit.alpha = 0.3f
        }

        private fun setGenerateLoading(loading: Boolean) {
            isAnimating = loading
            binding.btnGenerate.isEnabled = !loading
            binding.btnGenerate.alpha = if (loading) 0.3f else 1f
        }

        private fun handleGenerate() {
            if (isAnimating || viewModel.randomList.isEmpty()) return
            clearGeneratedResult()
            setGenerateLoading(true)
            generationJob = lifecycleScope.launch {
                try {
                    showLoading()
                    checkGenerationInternet()
                    val model = viewModel.randomList.random()
                    val bitmap = renderSuggestion(model)
                    checkGenerationInternet()
                    // Publish image and edit data together, only after the complete render succeeds.
                    binding.imvImage.setImageBitmap(bitmap)
                    binding.guidRandom.gone()
                    currentSuggestion = model
                    binding.btnEdit.isEnabled = true
                    binding.btnEdit.alpha = 1f
                } catch (cancelled: CancellationException) {
                    throw cancelled
                } catch (error: Exception) {
                    clearGeneratedResult()
                    if (!InternetHelper.isInternetAvailable(this@TrendingActivity)) {
                        pendingNoInternet = true
                    } else {
                        showToast(R.string.an_error_occurred)
                    }
                } finally {
                    networkWatchJob?.cancel()
                    setGenerateLoading(false)
                    withContext(NonCancellable) { dismissLoading() }
                    showPendingNoInternet()
                }
            }
            networkWatchJob = lifecycleScope.launch {
                while (isAnimating) {
                    if (!InternetHelper.isInternetAvailable(this@TrendingActivity)) {
                        interruptGenerationForNoInternet()
                        break
                    }
                    delay(250)
                }
            }
        }

        private fun checkGenerationInternet() {
            check(InternetHelper.isInternetAvailable(this)) { "Network lost during generation" }
        }

        private fun interruptGenerationForNoInternet() {
            if (!isAnimating) return
            pendingNoInternet = true
            clearGeneratedResult()
            generationJob?.cancel()
        }

        private fun showPendingNoInternet() {
            if (!pendingNoInternet || !lifecycle.currentState.isAtLeast(Lifecycle.State.RESUMED)) return
            pendingNoInternet = false
            showNoInternetDialog()
        }

        private fun showNoInternetDialog() {
            if (isFinishing || isDestroyed || noInternetDialog?.isShowing == true) return
            val dialog = YesNoDialog(
                this, R.string.no_internet, R.string.please_check_your_internet, isError = true
            )
            noInternetDialog = dialog
            dialog.show()
            dialog.onYesClick = {
                dialog.dismiss()
                hideNavigation()
            }
        }

        private suspend fun renderSuggestion(model: SuggestionModel): Bitmap = withContext(Dispatchers.IO) {
            if (model.pathInternalRandom.isNotEmpty()) {
                return@withContext loadLayerWithRetry(model.pathInternalRandom)
            }
            val paths = model.pathSelectedList.filter { it.isNotEmpty() }
            check(paths.isNotEmpty()) { "Suggestion has no layers" }
            val first = loadLayerWithRetry(paths.first())
            val width = (first.width / 2).coerceAtLeast(1)
            val height = (first.height / 2).coerceAtLeast(1)
            first.recycle()
            val layers = coroutineScope {
                paths.map { path -> async { loadLayerWithRetry(path, width, height) } }.awaitAll()
            }
            val combined = createBitmap(width, height)
            val canvas = Canvas(combined)
            layers.forEach { bitmap ->
                canvas.drawBitmap(bitmap, (width - bitmap.width) / 2f, (height - bitmap.height) / 2f, null)
                bitmap.recycle()
            }
            var previewPath: String? = null
            MediaHelper.saveBitmapToPreviewCache(this@TrendingActivity, combined).collect { state ->
                when (state) {
                    is SaveState.Success -> previewPath = state.path
                    is SaveState.Error -> throw state.exception
                    else -> Unit
                }
            }
            model.pathInternalRandom = checkNotNull(previewPath) { "Preview was not saved" }
            // The preview writer recycles its input bitmap; decode the saved result for display.
            loadLayerWithRetry(model.pathInternalRandom)
        }

        private suspend fun loadLayerWithRetry(
            path: String,
            width: Int? = null,
            height: Int? = null
        ): Bitmap {
            var lastError: Exception? = null
            repeat(MAX_LAYER_LOAD_ATTEMPTS) { attempt ->
                checkGenerationInternet()
                val request = Glide.with(applicationContext).asBitmap().load(path)
                val target = if (width != null && height != null) {
                    request.submit(width, height)
                } else {
                    request.submit()
                }
                try {
                    // Interrupt the blocking Glide wait when this generation is cancelled.
                    return runInterruptible(Dispatchers.IO) {
                        val bitmap = target.get()
                        checkNotNull(bitmap.copy(Bitmap.Config.ARGB_8888, false))
                    }
                } catch (cancelled: CancellationException) {
                    throw cancelled
                } catch (error: Exception) {
                    lastError = error
                } finally {
                    Glide.with(applicationContext).clear(target)
                }
                if (attempt < MAX_LAYER_LOAD_ATTEMPTS - 1) delay(RETRY_DELAY_MS * (attempt + 1))
            }
            throw lastError ?: IllegalStateException("Unable to load layer: $path")
        }

        companion object {
            private const val MAX_LAYER_LOAD_ATTEMPTS = 3
            private const val RETRY_DELAY_MS = 400L
        }

        private fun handleEdit() {
            if (isAnimating) return
            val suggestion = currentSuggestion ?: return
            customizeCharacterViewModel.positionSelected =
                dataViewModel.allData.value.indexOfFirst { it.avatar == suggestion.avatarPath }
            val selectedCharacter =
                dataViewModel.allData.value.getOrNull(customizeCharacterViewModel.positionSelected)
            viewModel.setIsDataAPI(selectedCharacter?.isFromAPI ?: false)
            viewModel.checkDataInternet(this) {
                lifecycleScope.launch {
                    showLoading()
                    withContext(Dispatchers.IO) {
                        MediaHelper.writeModelToFile(
                            this@TrendingActivity,
                            ValueKey.SUGGESTION_FILE_INTERNAL,
                            suggestion
                        )
                    }
                    val intent =
                        Intent(this@TrendingActivity, CustomizeCharacterActivity::class.java)
                    intent.putExtra(
                        IntentKey.INTENT_KEY,
                        customizeCharacterViewModel.positionSelected
                    )
                    intent.putExtra(IntentKey.STATUS_FROM_KEY, ValueKey.SUGGESTION)
                    val option = ActivityOptions.makeCustomAnimation(
                        this@TrendingActivity,
                        R.anim.slide_out_left,
                        R.anim.slide_in_right
                    )
                    dismissLoading()
                    showInterAll { startActivity(intent, option.toBundle()) }
                }
            }
        }

        override fun onWindowFocusChanged(hasFocus: Boolean) {
            super.onWindowFocusChanged(hasFocus)
            if (hasFocus) {
                applyUiCustomize()
                hideNavigation()
                window.decorView.removeCallbacks(reHideRunnable)
                window.decorView.postDelayed(reHideRunnable, 2000)
            } else {
                window.decorView.removeCallbacks(reHideRunnable)
            }
        }

        private val reHideRunnable = Runnable {
            applyUiCustomize()
            hideNavigation()
        }

        @Suppress("DEPRECATION")
        private fun applyUiCustomize() {
            window.addFlags(WindowManager.LayoutParams.FLAG_DRAWS_SYSTEM_BAR_BACKGROUNDS)
            window.statusBarColor = android.graphics.Color.TRANSPARENT
            window.navigationBarColor = android.graphics.Color.TRANSPARENT
            window.decorView.systemUiVisibility =
                View.SYSTEM_UI_FLAG_LAYOUT_STABLE or
                        View.SYSTEM_UI_FLAG_LAYOUT_FULLSCREEN or
                        View.SYSTEM_UI_FLAG_LAYOUT_HIDE_NAVIGATION or
                        View.SYSTEM_UI_FLAG_HIDE_NAVIGATION or
                        View.SYSTEM_UI_FLAG_IMMERSIVE_STICKY
        }


